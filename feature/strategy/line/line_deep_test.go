func strconvFormatFloat(v float64) string { return strconv.FormatFloat(v, 'f', -1, 64) }

func ohlcBars(bars [][4]float64) []*futures.Kline {
	out := make([]*futures.Kline, len(bars))
	for i, b := range bars {
		out[i] = &futures.Kline{Open: strconvFormatFloat(b[0]), High: strconvFormatFloat(b[1]), Low: strconvFormatFloat(b[2]), Close: strconvFormatFloat(b[3]), OpenTime: int64(1000 - i)}
	}
	return out
}

func closeBars(closes []float64) []*futures.Kline {
	out := make([]*futures.Kline, len(closes))
	for i, c := range closes {
		s := strconvFormatFloat(c)
		out[i] = &futures.Kline{Open: s, High: s, Low: s, Close: s, OpenTime: int64(1000 - i)}
	}
	return out
}

